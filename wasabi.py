import os
import sys
import subprocess
import re
import time

# --- Step 1. 依存ライブラリと外部ツールのインストール ---
print("=== 1. 必要な環境のインストール確認 ===")
try:
    import streamlit
    import pandas
    print("✅ Pythonライブラリ (streamlit, pandas) はインストール済みです。")
except ImportError:
    print("ጒ 必要なライブラリが見つからないため、インストールを開始します...")
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "streamlit", "pandas"])

if subprocess.call(["which", "cloudflared"], stdout=subprocess.DEVNULL) != 0:
    print("ጒ cloudflared が見つかりません。新規インストールを実行します...")
    subprocess.run("curl -L --output cloudflared.deb https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-linux-amd64.deb", shell=True)
    subprocess.run("dpkg -i cloudflared.deb", shell=True)
    subprocess.run("rm cloudflared.deb", shell=True)
    print("✅ cloudflared のセットアップが完了しました。")
else:
    print("✅ cloudflared はインストール済みです。")

# --- Step 2. 既存の起動プロセスをリセット ---
print("\n=== 2. バックグラウンドプロセスの初期化 ===")
subprocess.run("pkill -f 'streamlit run'", shell=True)
subprocess.run("pkill -f 'cloudflared'", shell=True)
time.sleep(2)
print("✅ 古いプロセスを安全にクリーンアップしました。")

# --- Step 3. Streamlitアプリの起動 ---
print("\n=== 3. 薬膳アプリサーバーの再起動 ===")
python_path = sys.executable
log_file = open("streamlit_run_v2.log", "w")
process_st = subprocess.Popen(
    [python_path, "-m", "streamlit", "run", "app.py", "--server.port", "8501"],
    stdout=log_file,
    stderr=log_file
)
time.sleep(3)
print("✅ Streamlitをポート8501で起動しました。")

# --- Step 4. Cloudflare トンネルの起動とURLの発行 ---
print("\n=== 4. 安全な公開用URL（トンネルアドレス）を生成中 ===")
process_cf = subprocess.Popen(
    ["cloudflared", "tunnel", "--url", "http://localhost:8501"],
    stdout=subprocess.PIPE,
    stderr=subprocess.STDOUT,
    text=True
)

url_found = False
for i in range(40):
    line = process_cf.stdout.readline()
    match = re.search(r'https://[a-zA-Z0-9-]+\.trycloudflare\.com', line)
    if match:
        print("\nጡ 準備が完了しました！以下の新しいURLからWebアプリにアクセスできます：")
        print("’", match.group(0))
        url_found = True
        break
    time.sleep(0.5)

if not url_found:
    print("❌ URLの自動検出に時間がかかっています。少し待ってからブラウザをリロードするか、このセルを再実行してください。")



